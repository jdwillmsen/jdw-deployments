#!/usr/bin/env python3
"""Keep the world-guard source inside the chart values that run it.

An init container's `args` is rendered by plain toYaml, never tpl, and the
charts mount no ConfigMap for it, so the guard's source has to sit in the values
file as text. That text must not drift from tools/world-guard/world_guard.py, which
the unit tests exercise, so it is generated:

  embed.py --write VALUES...   rewrite the block between the markers in each file
  embed.py --check VALUES...   fail if a block differs from world_guard.py

A values file carries the block as

      args:
        # BEGIN world-guard (generated by tools/world-guard/embed.py from world_guard.py; edit that, then --write)
        - |
          ...
        # END world-guard

Run with no arguments to check every chart values file that has a block.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SOURCE = os.path.join(HERE, "world_guard.py")
BEGIN = re.compile(r"^(?P<indent> *)# BEGIN world-guard\b.*$", re.M)
END = "# END world-guard"


def block(indent):
    with open(SOURCE) as f:
        src = f.read()
    if "\t" in src or any(line != line.rstrip() for line in src.splitlines()):
        raise SystemExit("world_guard.py has tabs or trailing whitespace; a YAML block scalar would not round-trip")
    pad = indent + "  "
    body = "".join((pad + line if line.strip() else line) for line in src.splitlines(True))
    return "%s- |\n%s" % (indent, body)


def render(text):
    """Return text with every marked block regenerated, and how many blocks there were."""
    out, pos, n = [], 0, 0
    for m in BEGIN.finditer(text):
        if m.start() < pos:
            continue
        end = text.find(END, m.end())
        if end < 0:
            raise SystemExit("BEGIN world-guard with no END world-guard")
        line_end = text.index("\n", m.end()) + 1
        end_line_start = text.rfind("\n", 0, end) + 1
        out.append(text[pos:line_end])
        out.append(block(m.group("indent")))
        pos = end_line_start
        n += 1
    out.append(text[pos:])
    return "".join(out), n


def files(args):
    if args:
        return args
    found = glob.glob(os.path.join(ROOT, "charts", "*", "values*.yaml"))
    return sorted(p for p in found if has_block(p))


def has_block(path):
    with open(path) as f:
        return "# BEGIN world-guard" in f.read()


def main(argv):
    mode = argv[1] if len(argv) > 1 else "--check"
    if mode not in ("--write", "--check"):
        print(__doc__)
        return 64
    rc = 0
    for path in files(argv[2:]):
        with open(path) as f:
            old = f.read()
        new, n = render(old)
        if n == 0:
            print("%s: no world-guard block" % path)
            rc = 1
        elif new == old:
            print("%s: in sync (%d block)" % (path, n))
        elif mode == "--write":
            with open(path, "w") as f:
                f.write(new)
            print("%s: rewritten" % path)
        else:
            print("%s: DIFFERS from tools/world-guard/world_guard.py; run tools/world-guard/embed.py --write" % path)
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv))
